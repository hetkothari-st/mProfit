/**
 * Writes the data migration that ships RBI's 91-day T-bill auction history
 * (`TBILL_91D`, Jul 2012 – Jul 2018) to every database.
 *
 * Run:
 *   pnpm --filter @everypaisa/api exec tsx scripts/generate-rbi-tbill-migration.ts <migration-dir>
 *
 * Why a migration and not a feed: the history is closed — those auctions will
 * never be restated — and rbi.org.in answers the shared transport with HTTP
 * 418. So production never calls RBI; the rows travel with the schema. The
 * input is the six edition tables committed as golden fixtures
 * (`test/fixtures/mf/benchmarks/rbi-tbill-handbook-<id>.table.html`), parsed
 * by the same `fetchRbiTbillHistory` the tests pin, so the SQL can be
 * regenerated byte-for-byte from the repository alone.
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Decimal } from 'decimal.js';
import {
  fetchRbiTbillHistory,
  RBI_TBILL_ADAPTER_ID,
  RBI_TBILL_HISTORY_START,
} from '../src/priceFeeds/rbiTbillHandbook.v1.js';
import { RBI_TBILL_SERIES } from '../src/priceFeeds/rbiTbillHandbook.parse.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const fixtures = resolve(here, '../test/fixtures/mf/benchmarks');
const iso = (d: Date): string => d.toISOString().slice(0, 10);

async function main(): Promise<void> {
  const outDir = process.argv[2];
  if (outDir === undefined) throw new Error('usage: generate-rbi-tbill-migration <migration-dir>');

  const out = await fetchRbiTbillHistory(
    { from: new Date(`${RBI_TBILL_HISTORY_START}T00:00:00Z`), to: new Date('2018-07-31T00:00:00Z') },
    {
      fetchText: async (url) => {
        const id = /id=(\d+)/.exec(url)?.[1];
        return { ok: true, text: await readFile(`${fixtures}/rbi-tbill-handbook-${id}.table.html`, 'utf8') };
      },
    },
  );
  if (!out.ok) throw new Error(`parse failed: ${out.detail}`);

  const values = out.rows.map((r) => {
    const day = iso(r.date);
    // Same precision and hash as riskFreeRateJob.persistRows, so a later
    // job run over these dates sees identical rows and writes nothing.
    const rate = new Decimal(r.ratePct.toString()).toFixed(6, Decimal.ROUND_HALF_EVEN);
    const hash = createHash('sha256')
      .update(`riskfree:${RBI_TBILL_ADAPTER_ID}:${RBI_TBILL_SERIES}:${day}:${rate}`)
      .digest('hex');
    return `  ('rbi91_${day.replace(/-/g, '')}', '${RBI_TBILL_SERIES}', '${day}', ${rate}, '${hash}')`;
  });

  const sql = `-- =============================================================================
-- RBI 91-day T-bill primary-auction cut-off yields, ${iso(out.rows[0]!.date)} .. ${iso(out.rows.at(-1)!.date)}.
--
-- GENERATED by scripts/generate-rbi-tbill-migration.ts from the six RBI
-- Handbook edition tables committed under test/fixtures/mf/benchmarks/.
-- Do not edit by hand; regenerate.
--
-- ${out.rows.length} weekly auctions, series TBILL_91D. The MF metrics use them only for
-- dates before FBIL's curve begins (2017-08-23) — see ACTIVE_RISK_FREE_SERIES_START
-- in riskFree.parse.ts. ${out.failures.length} auctions are absent because RBI rejected every
-- bid and printed no cut-off (27-Jan-2016, 24-Feb-2016).
-- =============================================================================

INSERT INTO "RiskFreeRate" ("id", "series", "date", "ratePct", "sourceHash")
VALUES
${values.join(',\n')}
ON CONFLICT ("series", "date") DO NOTHING;
`;
  await mkdir(outDir, { recursive: true });
  await writeFile(resolve(outDir, 'migration.sql'), sql, 'utf8');
  console.log(`wrote ${out.rows.length} rows to ${outDir}/migration.sql`);
}

void main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
