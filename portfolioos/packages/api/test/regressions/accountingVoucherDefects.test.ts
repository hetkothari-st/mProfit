import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { createTestScope, prisma, type TestScope } from '../helpers/db.js';
import { deleteVoucher, nextVoucherNo } from '../../src/services/accounting/accounting.service.js';

let scope: TestScope;
beforeAll(async () => {
  scope = await createTestScope('acct-vouchers');
});
afterAll(async () => {
  await scope.cleanup();
});

const voucher = (voucherNo: string, isAutoGenerated: boolean, type: 'SALES' | 'JOURNAL' = 'SALES') =>
  prisma.voucher.create({
    data: { userId: scope.userId, type, voucherNo, date: new Date('2026-04-01'), isAutoGenerated },
  });

describe('next voucher number', () => {
  it('starts the series at 0001 when only auto vouchers exist', async () => {
    await scope.runAs(async () => {
      await voucher('AUTO-SELL-cm9x2k7ab0001qz8v3h4j5k6l', true);
      expect(await nextVoucherNo(scope.userId, 'SALES')).toBe('SA0001');
    });
  });

  it('compares numbers, not text (JO9999 → JO10000 → JO10001)', async () => {
    await scope.runAs(async () => {
      await voucher('JO9999', false, 'JOURNAL');
      await voucher('JO10000', false, 'JOURNAL');
      expect(await nextVoucherNo(scope.userId, 'JOURNAL')).toBe('JO10001');
    });
  });
});

describe('deleting an auto voucher', () => {
  it('is refused with a reason, since the next sync would recreate it', async () => {
    await scope.runAs(async () => {
      const v = await voucher('AUTO-SELL-deltest', true);
      await expect(deleteVoucher(scope.userId, v.id)).rejects.toMatchObject({ statusCode: 409 });
      expect(await prisma.voucher.findUnique({ where: { id: v.id } })).not.toBeNull();
    });
  });

  it('a manual voucher still deletes', async () => {
    await scope.runAs(async () => {
      const v = await voucher('SA0100', false);
      await deleteVoucher(scope.userId, v.id);
      expect(await prisma.voucher.findUnique({ where: { id: v.id } })).toBeNull();
    });
  });
});
